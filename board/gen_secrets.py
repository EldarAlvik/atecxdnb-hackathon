"""Generate board/secrets.h (git-ignored) from the repo-root .env.

    uv run python board/gen_secrets.py

project.yaml's globals do `#include "../../secrets.h"`, which resolves from
board/build/src/main.cpp to board/secrets.h. Values are never printed.
"""
from pathlib import Path

REQUIRED = ["ANTHROPIC_API_KEY", "DEEPGRAM_API_KEY", "WIFI_SSID"]
OPTIONAL = ["WIFI_PASSWORD"]

here = Path(__file__).resolve().parent
env_path = here.parent / ".env"
out_path = here / "secrets.h"


def parse_env(path: Path) -> dict:
    env = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip().removeprefix("export ").strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        env[key] = value
    return env


def c_string(value: str) -> str:
    out = []
    for byte in value.encode("utf-8"):
        ch = chr(byte)
        if ch in "\\\"":
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F and ch != "?":
            out.append(ch)
        else:
            out.append("\\%03o" % byte)  # octal escape: safe for any byte
    return '"' + "".join(out) + '"'


env = parse_env(env_path)
missing = [k for k in REQUIRED if not env.get(k)]
if missing:
    raise SystemExit(f"error: {env_path} is missing: {', '.join(missing)}")

lines = [
    "// GENERATED by board/gen_secrets.py from .env -- DO NOT COMMIT (git-ignored).",
    "#pragma once",
]
for key in REQUIRED + OPTIONAL:
    lines.append(f"#define SG_{key} {c_string(env.get(key, ''))}")
out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out_path} ({', '.join(f'{k}: {len(env.get(k, ''))} chars' for k in REQUIRED + OPTIONAL)})")
